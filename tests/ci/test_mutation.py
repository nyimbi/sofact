class TestTheRateIsMeasured:
	"""A real kill rate, over a real suite, in a real subprocess."""

	async def test_a_strong_suite_kills_more_than_a_weak_one(self, tmp_path: Path) -> None:
		"""The instrument discriminating, which is the only thing that makes it one.

		Both suites run the same module through the same operator set. If the strong
		suite did not score higher, the measurement would be reporting the operator set
		rather than the suite — and the operator set is fixed, so that number would be
		the same for every module in the factory.
		"""
		weak = await measure_strength(
			tree_for(tmp_path / "weak", suite=WEAK_SUITE), module=MODULE, suite=suite_argv()
		)
		strong = await measure_strength(
			tree_for(tmp_path / "strong", suite=STRONG_SUITE), module=MODULE, suite=suite_argv()
		)

		assert weak.measured_strength is not None, weak.refusal
		assert strong.measured_strength is not None, strong.refusal
		assert strong.measured_strength > weak.measured_strength, (
			f"a suite pinning both branches scored {strong.measured_strength:.3f} against "
			f"{weak.measured_strength:.3f} for one asserting a single path"
		)

	async def test_the_raw_counts_are_kept_beside_the_rate(self, tmp_path: Path) -> None:
		"""A rate without its counts is a number a reader cannot check.

		The three outcomes partition the mutants, and the assertion is that they do —
		a mutant counted in two buckets would move the rate twice.
		"""
		report = await measure_strength(tree_for(tmp_path), module=MODULE, suite=suite_argv())

		total = (
			len(report.killed)
			+ len(report.survived)
			+ len(report.discarded)
			+ len(report.timed_out)
		)
		assert total == len(report.results)
		assert report.scored == len(report.results) - len(report.discarded)
		assert report.measured_strength == pytest.approx(len(report.killed) / report.scored), (
			"the rate must be recomputable from the counts it ships with"
		)

	async def test_the_workspace_is_never_mutated(self, tmp_path: Path) -> None:
		"""FR-006's cache key is ``digest_tree``, so a mutant left behind would invalidate
		a verdict nothing touched.

		Asserted on the digest rather than on the source, because the digest is what the
		cache actually reads — a leftover file the excludes swallowed would still move it.
		"""
		workspace = tree_for(tmp_path)
		before = digest_tree(workspace)

		await measure_strength(workspace, module=MODULE, suite=suite_argv())

		assert digest_tree(workspace) == before, (
			"a mutant run must leave the measured tree byte-identical"
		)
		assert (workspace / MODULE).read_text(encoding="utf-8") == GOOD_MODULE


class TestTheThreeOutcomesAreNotAScale:
	"""Killed, discarded and timed out are three facts, and only one is evidence."""

	async def test_a_non_compiling_mutant_is_discarded_not_killed(self, tmp_path: Path) -> None:
		"""A mutant that never parsed was never run, so it says nothing about the suite.

		The defect this closes is a *count*: an engine that scored a syntax error as a
		kill would let a typo raise the score, and the score is the thing an operator acts
		on. Driven by a real operator whose rewrite genuinely does not compile — a
		transformer that renames a call to a name no longer in scope — rather than by a
		hand-built string, so the discard branch is reached through the same code path a
		shipped operator would reach it by.
		"""
		report = await measure_strength(
			tree_for(tmp_path),
			module=MODULE,
			suite=suite_argv(),
			operators=(_NON_COMPILING,),
		)

		assert len(report.results) == 1, report.results
		result = report.results[0]
		assert result.outcome is MutationOutcome.DISCARDED, result
		assert result.outcome is not MutationOutcome.KILLED
		assert "does not compile" in result.detail
		assert report.killed == (), "a mutant that never ran must not appear as a kill"
		assert report.scored == 0, "a discarded mutant is not scored"
		assert report.measured_strength is None, (
			"a rate over zero scored mutants is undefined, not zero"
		)

	async def test_a_real_run_discards_nothing_from_the_shipped_set(self, tmp_path: Path) -> None:
		"""The complement, and it is the useful direction: the five shipped operators all
		produce compiling mutants on an ordinary module, so a discard in a real report is
		a signal rather than routine noise."""
		report = await measure_strength(tree_for(tmp_path), module=MODULE, suite=suite_argv())

		assert report.discarded == (), [r.detail for r in report.discarded]
		assert report.measured_strength is not None

	async def test_a_timed_out_mutant_is_not_counted_as_killed(self, tmp_path: Path) -> None:
		"""A suite that did not finish did not agree, and did not disagree either.

		Reaching this branch needs the *baseline* to finish and a mutant not to: a slow
		suite everywhere would time out on the pristine tree too, and the report would
		refuse before any mutant was ever produced — which is how this test first read
		green while exercising nothing. So the operator below makes the module hang, and
		the pristine module does not.
		"""
		report = await measure_strength(
			tree_for(tmp_path),
			module=MODULE,
			suite=suite_argv(),
			timeout=5.0,
			operators=(_HANGING,),
		)

		assert len(report.results) == 1, report.results
		result = report.results[0]
		assert result.outcome is MutationOutcome.TIMED_OUT, result
		assert report.killed == (), "a mutant the suite never judged is not a kill"
		assert report.scored == 1, (
			"a timed-out mutant stays in the denominator: it was offered and no verdict "
			"came back, which is a hole in the measurement rather than a kill"
		)
		assert report.refusal is StrengthRefusal.BELOW_THE_FLOOR, (
			"one scored mutant is below the floor, so even this report withholds a number — "
			"which is the same discipline the timeout rule enforces one level down"
		)
		assert report.measured_strength is None
		assert report.timed_out == (result,), "the timeout is reported, not swallowed"


class TestTheNumberIsWithheld:
	"""NFR-024: never report a target the product has not measured."""

	async def test_a_module_that_does_not_exist_is_refused_by_name(self, tmp_path: Path) -> None:
		report = await measure_strength(tree_for(tmp_path), module="nowhere.py", suite=suite_argv())

		assert report.refusal is StrengthRefusal.NO_MODULE
		assert report.measured_strength is None
		assert not report.measured
		assert "not measured" in report.rendered

	async def test_a_module_that_does_not_parse_is_refused_by_name(self, tmp_path: Path) -> None:
		workspace = tree_for(tmp_path, module="def broken(:\n")
		report = await measure_strength(workspace, module=MODULE, suite=suite_argv())

		assert report.refusal is StrengthRefusal.NO_MODULE
		assert report.measured_strength is None

	async def test_a_suite_that_already_fails_yields_no_number(self, tmp_path: Path) -> None:
		"""Every mutant would "flip" a suite that was already red, so the report would
		state a perfect score for a suite that was broken before the measurement began."""
		workspace = tree_for(tmp_path, suite=BROKEN_SUITE)
		report = await measure_strength(workspace, module=MODULE, suite=suite_argv())

		assert report.refusal is StrengthRefusal.MODULE_DID_NOT_IMPORT
		assert report.measured_strength is None, (
			"a red baseline must not be laundered into a kill rate"
		)

	async def test_below_the_floor_there_is_no_number(self, tmp_path: Path) -> None:
		"""Three mutants killed is 1.000 and means nothing.

		The module here has almost nothing to mutate — one return, no comparison — so the
		operator set finds fewer mutants than the floor and the report says so instead of
		printing a rate.
		"""
		workspace = tree_for(tmp_path, module="VALUE = 1\n", suite=TRIVIAL_SUITE)
		report = await measure_strength(workspace, module=MODULE, suite=suite_argv())

		assert report.refusal is StrengthRefusal.BELOW_THE_FLOOR
		assert report.measured_strength is None
		assert report.results, "the mutants found are still reported, with the refusal"
		assert len(report.results) - len(report.discarded) < MINIMUM_MUTANTS_FOR_A_NUMBER

	async def test_no_suite_is_a_named_refusal_rather_than_an_assertion(self) -> None:
		"""A caller with no suite has nothing whose strength could be measured, and that
		is an ordinary state rather than a fault."""
		with pytest.raises(AssertionError, match="names the suite"):
			await measure_strength(Path("."), module=MODULE, suite=())

	def test_a_report_with_neither_results_nor_refusal_is_refused(self) -> None:
		"""The type refuses the one shape that would be a lie: an empty measurement
		presented as a measurement."""
		with pytest.raises(AssertionError, match="must carry its mutants"):
			MutationReport(module="subject.py", operator_set=("comparison_swap",), results=())


TRIVIAL_SUITE = '''\
"""A suite over a module with a single constant in it."""

import subject

assert subject.VALUE == 1, "the one thing there is to check"
'''


class TestTheOperatorSetIsClosedAndNamed:
	"""A rate is a statement about *which* mutants, so the set is asserted, not assumed."""

	def test_every_operator_is_named_and_described(self) -> None:
		assert OPERATORS, "an empty operator set would measure nothing and report 1.0"
		names = [operator.name for operator in OPERATORS]
		assert len(set(names)) == len(names), "two operators sharing a name are not comparable"
		for operator in OPERATORS:
			assert operator.description.strip(), f"{operator.name} must say what mistake it makes"

	def test_an_operator_that_finds_nothing_returns_none_rather_than_its_input(self) -> None:
		"""A mutant identical to its parent would be scored as surviving, and would
		depress the rate for a reason about the operator set rather than the suite.

		Through ``MutationOperator.apply`` — the surface the engine actually calls — rather
		than the transformer class behind it, because the property belongs to the operator:
		a rewrite that returned an unchanged tree would make every operator fire on every
		module and the denominator would count mutants that are their own parent.
		"""
		swap = next(operator for operator in OPERATORS if operator.name == "comparison_swap")

		assert swap.apply(ast.parse("VALUE = 1\n")) is None, (
			"a module with no comparison must produce no mutant, not an unchanged one"
		)
		assert swap.apply(ast.parse("if a < b:\n\tpass\n")) is not None, (
			"the canary: the same operator must fire on a module that does hold a comparison"
		)

	def test_every_operator_changes_something_in_a_module_that_has_the_shape(self) -> None:
		"""The other half: each operator must be able to fire, or it is dead weight in the
		denominator and the reported set names an operator that never ran."""
		tree = ast.parse(GOOD_MODULE)
		for operator in OPERATORS:
			assert operator.apply(tree) is not None, (
				f"{operator.name} found nothing to change in a module with a comparison, a "
				"branch, a computed return, an integer literal and an expression statement"
			)

	def test_the_set_is_five_specific_mistakes(self) -> None:
		"""Named rather than counted, so an operator added or removed is visible here."""
		assert {operator.name for operator in OPERATORS} == {
			"comparison_swap",
			"boolean_negate",
			"return_none",
			"constant_off_by_one",
			"statement_delete",
		}


class TestTheGateStaysShut:
	"""The number is recorded and rendered; it does not decide anything."""

	def test_the_theta_gate_is_still_not_built(self) -> None:
		"""``THETA_GATE_BUILT`` stays ``False``. Measuring a strength is not the same as
		being able to decide FR-024–FR-035's gate, and this build does not consult
		``L4_GATE_THETA`` anywhere — the number exists so the report can state it, not so
		a ceiling can move."""
		from sofact.views import L4_GATE_THETA, THETA_GATE_BUILT

		assert THETA_GATE_BUILT is False
		assert pytest.approx(0.80) == L4_GATE_THETA


def _splice_unparseable(tree: ast.Module) -> ast.Module | None:
	"""A rewrite whose *unparsed source* does not parse, through the real write path.

	The failure has to be introduced where the source is produced: every well-formed AST
	unparses to well-formed Python, so the only way to reach the discard branch from a
	transformer is a node whose identifier is not one — ``ast.Name(id="a b")`` unparses to
	``a b``, which the parser rejects. That is the shape a genuinely broken operator has,
	and driving the branch this way means the test exercises the same write-then-reparse
	guard a shipped operator would hit.
	"""

	class _Splice(ast.NodeTransformer):
		changed = True

		def visit_Return(self, node: ast.Return) -> ast.AST:
			if node.value is not None:
				node.value = ast.Name(id="a b", ctx=ast.Load())
			return node

	working = ast.parse(ast.unparse(tree))
	_Splice().visit(working)
	ast.fix_missing_locations(working)
	return working


_NON_COMPILING = MutationOperator(
	name="non_compiling",
	description="a rewrite whose source does not parse, to drive the discard branch",
	apply=_splice_unparseable,
)


def _make_the_module_hang(tree: ast.Module) -> ast.Module | None:
	"""A rewrite that makes the module itself hang, so the *suite* times out.

	The hang has to be in the module rather than in the suite: the pristine tree must
	finish, or the report refuses before producing a mutant and the ``TIMED_OUT`` branch
	is never reached. ``while True: pass`` at module scope does it, and the mutant still
	compiles — a discard would exercise the wrong branch.
	"""

	working = ast.parse(ast.unparse(tree))
	working.body.append(ast.While(test=ast.Constant(value=True), body=[ast.Pass()], orelse=[]))
	ast.fix_missing_locations(working)
	return working


_HANGING = MutationOperator(
	name="hanging",
	description="a module that never finishes importing, to drive the timeout branch",
	apply=_make_the_module_hang,
)
