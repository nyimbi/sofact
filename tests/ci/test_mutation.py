"""FR-118's measured strength: a kill rate that refuses to be a score.

The failure this instrument is built against is a *number* — a rate over three mutants,
printed under the word "measured", that an operator acts on. So the substance here is
what the report withholds and why: below the floor there is no number, a mutant that did
not compile is not a kill, and a suite that hangs is not a suite that agreed.

Everything runs real: a real module on a real filesystem, a real ``python3`` suite
process, and the real operator set. The mutants are the only thing generated, and they
are generated by the code under test — which is why the operator set's *membership* is
asserted rather than assumed.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

import pytest

from sofact.execution import digest_tree
from sofact.mutation import (
	MINIMUM_MUTANTS_FOR_A_NUMBER,
	OPERATORS,
	MutationOperator,
	MutationOutcome,
	MutationReport,
	StrengthRefusal,
	measure_strength,
)

MODULE = "subject.py"
SUITE = "test_subject.py"

GOOD_MODULE = '''\
"""A tiny module with a boundary and a branch, so every operator finds work."""


def classify(value, limit):
	if value < limit:
		return "under"
	return "over"


def total(items):
	count = 0
	for item in items:
		count = count + item
	return count
'''

WEAK_SUITE = '''\
"""A suite that exercises one path and asserts one thing.

A plain script rather than a pytest module, and that is a cost decision with a
correctness argument behind it: the verdict this instrument reads is an *exit code*, and
a script asserts its way to one exactly as a runner does. Paying a test-runner's start-up
per mutant would put a five-minute floor under every measurement, and a gate nobody can
afford to run is a gate that gets turned off.
"""

import subject

assert subject.classify(1, 10) == "under", "the under branch"
'''

STRONG_SUITE = '''\
"""A suite that pins the boundary, both branches, and the loop.

Each assertion is a separate statement, so the script's exit code is the conjunction of
all of them and a mutant that breaks any one is killed.
"""

import subject

assert subject.classify(1, 10) == "under", "the under branch"
assert subject.classify(10, 10) == "over", "the boundary itself"
assert subject.classify(99, 10) == "over", "the over branch"
assert subject.total([1, 2, 3]) == 6, "the loop accumulates"
assert subject.total([]) == 0, "the empty case"
'''

BROKEN_SUITE = '''\
"""A suite that fails before any mutation, so nothing can be measured against it."""

import subject

assert subject.total([1]) == 999, "this is wrong on the pristine module too"
'''


def tree_for(tmp_path: Path, *, module: str = GOOD_MODULE, suite: str = STRONG_SUITE) -> Path:
	"""A real workspace holding the module and its suite."""
	workspace = tmp_path / "ws"
	workspace.mkdir(parents=True, exist_ok=True)
	(workspace / MODULE).write_text(module, encoding="utf-8")
	(workspace / SUITE).write_text(suite, encoding="utf-8")
	return workspace


def suite_argv() -> tuple[str, ...]:
	"""The suite command, run the way the factory runs anything: a real interpreter."""
	return (sys.executable, SUITE)


